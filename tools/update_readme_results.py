"""Generate the marked README result section, or verify it with --check."""
from __future__ import annotations

import argparse
import difflib
from pathlib import Path
import sys

if __package__:
    from . import show_results as viewer
else:
    import show_results as viewer

BEGIN = "<!-- BEGIN AUTO-GENERATED MEASURED RESULTS -->"
END = "<!-- END AUTO-GENERATED MEASURED RESULTS -->"


def render_markdown(data):
    p, d, v = (data[k] for k in ("provenance", "determinism", "verification"))
    a, b = (data["monte_carlo"][c] for c in ("case_a", "case_b"))
    lines = [BEGIN, "## Measured results", "",
             f'**Reportable campaign:** `{p["results_dir"]}/`<br>',
             f'**Scientific freeze:** `{p["freeze_tag"]}`<br>',
             f'**Freeze commit:** `{p["freeze_commit"]}`<br>',
             f'**Artifact packaging:** `{p["artifact_release"]}`', "",
             "| Metric | Case A | Case B |", "|---|---:|---:|"]
    hashes = [data["cases"][c]["bundle_sha256"] for c in ("case_a", "case_b")]
    lines.append(f"| Bundle SHA-256 | `{hashes[0]}` | `{hashes[1]}` |")
    for metric in (*viewer.METRIC_ORDER, "GD", "GD_min"):
        values = [data["metrics"][c][metric]["value"] for c in ("case_a", "case_b")]
        label = f'GD({data["metrics"]["case_a"]["GD"]["threshold"]})' if metric == "GD" else metric
        formatted = [viewer._fmt(x, 4 if metric in ("RCY", "NDR") and x not in (0, 1) else 3) for x in values]
        lines.append(f"| {label} | {formatted[0]} | {formatted[1]} |")
    lines += ["", f'**Determinism:** TD = {d["TD"]:.3f}; {d["passed"]}/{d["total"]} executions passed ({d["runs_per_case"]} per case).', "",
              f'**Monte Carlo:** K = {a["draws_K"]:,} per evaluated risk in Case A; '
              f'K = {b["draws_K"]:,} in Case B. Case A max FP_heat = {a["max_FP_heat"]:.6f} '
              f'(MCSE {a["max_FP_heat_mcse"]:.6f}); FP_C* = {a["max_FP_cstar"]:g} '
              f'in Case A and {b["max_FP_cstar"]:g} in Case B. '
              f'Observed Case A C* membership changes: {a["cstar_changes_observed"]}.', "",
              f'**Frozen campaign verification:** {v["tests_passed"]}/{v["tests_total"]} tests; '
              f'adversarial corpus {v["adversarial_passed"]}/{v["adversarial_total"]}; '
              f'structural checks {v["structural_passed"]}/{v["structural_total"]}; '
              f'{v["property_count"]} property tests / {v["generated_examples"]:,} generated Hypothesis examples; '
              f'{v["clean_queries_per_case"]} clean traceability queries per case, all empty; '
              f'{v["negative_controls_detected"]}/{v["negative_controls_total"]} negative controls detected.', "",
              "**Measured cross-platform evidence:**", "",
              "| OS / environment | Architecture | Python | TD | Hashes |",
              "|---|---|---|---:|---|"]
    for leg in data["cross_platform"]:
        lines.append(f'| {leg["os"].split("-")[0]} / {leg["leg"]} | {leg["arch"]} | {leg["python"]} | {leg["TD"]:.3f} | match |')
    lines += ["", viewer.headline(data)["claim_boundary"], "", "```bash", "make results", "```", "",
              "Print the complete reportable result set directly from the machine-generated",
              "final_v2 evidence. After `make install`, use `make results`; alternatively run",
              "`python tools/show_results.py` or `python tools/show_results.py --json`.", "",
              "This section is generated by `make readme-results`. Check it without modifying",
              "README with `make verify-readme-results` or",
              "`python tools/update_readme_results.py --check`.", END]
    return "\n".join(lines)


def replace_block(text, block):
    if text.count(BEGIN) != 1 or text.count(END) != 1:
        raise ValueError("README must contain exactly one pair of measured-results markers")
    start, end = text.index(BEGIN), text.index(END)
    if end < start:
        raise ValueError("README measured-results markers are reversed")
    return text[:start] + block + text[end + len(END):]


def render_provenance(data):
    lines = ["# Result display provenance", "",
             "Generated from `tools.show_results.load_results()` provenance records.",
             "Empirical evidence is read from final_v2. Editorial labels and packaging metadata",
             "are identified separately. Arithmetic in field descriptions only aggregates recorded counts.",
             "The viewer verifies final_v2 inventory hashes against MANIFEST.json and runs the",
             "existing paper-result map verifier and independent cross-checks before rendering.",
             "A missing local freeze tag is skipped by that verifier; recorded freeze evidence remains checked.",
             "No machine-readable ieee-check outcome is present in final_v2, so none is claimed.", "",
             "| Displayed result | Source file | JSON/CSV field | Terminal | README |",
             "|---|---|---|---|---|"]
    for row in data["_provenance_rows"]:
        lines.append("| " + " | ".join([row["displayed_result"], '`' + row["source_file"] + '`',
                                        '`' + row["field"] + '`', "yes" if row["terminal"] else "no",
                                        "yes" if row["readme"] else "no"]) + " |")
    return "\n".join(lines) + "\n"


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    try:
        data = viewer.load_results()
        if not data["_consistency"]["ok"]:
            raise ValueError("inconsistent evidence: " + "; ".join(data["_consistency"]["findings"]))
        path = Path(viewer.REPO_ROOT) / "README.md"
        original = path.read_bytes().decode("utf-8")
        expected = replace_block(original, render_markdown(data))
        if args.check:
            if original != expected:
                print("README measured results are stale; run make readme-results.", file=sys.stderr)
                print("".join(difflib.unified_diff(original.splitlines(True), expected.splitlines(True),
                                                 fromfile="README.md", tofile="generated README.md")), file=sys.stderr)
                return 1
            print("README measured results match final_v2 evidence.")
        else:
            path.write_bytes(expected.encode("utf-8"))
            print("Updated only the marked README measured-results block.")
    except (viewer.MissingEvidence, OSError, ValueError, KeyError, TypeError) as exc:
        print("ERROR: " + str(exc), file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
