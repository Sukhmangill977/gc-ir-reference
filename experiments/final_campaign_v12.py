"""The final v5 campaign driver (Paper 2 v1.2).

    python -m experiments.final_campaign_v12 --final-v5

This is the authoritative, single-command final campaign: it actually
executes every mandatory experiment, writes machine-readable results under
results/final_v5/, and exits non-zero if ANY mandatory step fails or was
skipped. It does not print "final" without doing the work, and it does not
copy results/development_v12/*.json into results/final_v5/ to satisfy a
checker -- every file under results/final_v5/ is either freshly generated by
a --phase final_v5 --output results/final_v5 invocation of the same scripts
that produced results/development_v12/, or explicitly copied with its
provenance recorded (cross-environment CI evidence and the pre-freeze
reconciliation documents, which are not per-run regenerable).

Intended use: run this from a clean checkout of the exact candidate commit
(ultimately, a clean `git worktree add --detach` of the preregister-tier0-v5
tag) -- see results/development_v12/RECONCILIATION_BEFORE_EXECUTION.md for
why a dirty working tree's output must never be treated as the final
campaign. Running it before that tag exists (as a pre-freeze dry run, to
validate the driver itself) is fine, but that run's results/final_v5/ output
must be discarded/regenerated once the real tagged run happens -- this
script does not know or care which situation it is in, so the caller is
responsible for that distinction.
"""

from __future__ import annotations

import argparse
import csv
import json
import os
import shutil
import subprocess
import sys
import time

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(REPO_ROOT, "src"))

OUT_DIR = os.path.join(REPO_ROOT, "results", "final_v5")
DEV_DIR = os.path.join(REPO_ROOT, "results", "development_v12")
PHASE = "final_v5"


def _git(*args):
    try:
        return subprocess.check_output(
            ["git"] + list(args), cwd=REPO_ROOT, stderr=subprocess.DEVNULL
        ).decode("utf-8").strip()
    except Exception:  # noqa: BLE001
        return None


class Ledger:
    def __init__(self):
        self.rows = []
        self.commit = _git("rev-parse", "HEAD") or "UNKNOWN"

    def add(self, test_id, category, command, case, expected, actual, status,
             environment_desc="local host", evidence_path="", input_hash="", output_hash=""):
        self.rows.append({
            "TEST_ID": test_id, "CATEGORY": category, "COMMAND": command, "CASE": case,
            "EXPECTED": expected, "ACTUAL": actual, "PASS_FAIL": status,
            "GIT_SHA": self.commit, "ENVIRONMENT": environment_desc,
            "INPUT_HASH": input_hash, "OUTPUT_HASH": output_hash,
            "RESULT_FILE": evidence_path,
            "TIMESTAMP": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        })

    def write(self, out_dir):
        csv_path = os.path.join(out_dir, "TEST_LEDGER.csv")
        fieldnames = ["TEST_ID", "CATEGORY", "COMMAND", "CASE", "EXPECTED", "ACTUAL",
                      "PASS_FAIL", "GIT_SHA", "ENVIRONMENT", "INPUT_HASH", "OUTPUT_HASH",
                      "RESULT_FILE", "TIMESTAMP"]
        with open(csv_path, "w", encoding="utf-8", newline="") as handle:
            writer = csv.DictWriter(handle, fieldnames=fieldnames)
            writer.writeheader()
            for row in self.rows:
                writer.writerow(row)

        total = len(self.rows)
        passed = sum(1 for r in self.rows if r["PASS_FAIL"] == "PASS")
        failed = sum(1 for r in self.rows if r["PASS_FAIL"] == "FAIL")
        skipped = sum(1 for r in self.rows if r["PASS_FAIL"] == "SKIPPED")
        not_run = sum(1 for r in self.rows if r["PASS_FAIL"] == "NOT_RUN")

        summary_path = os.path.join(out_dir, "TEST_LEDGER_SUMMARY.md")
        with open(summary_path, "w", encoding="utf-8") as handle:
            handle.write("# Test ledger summary -- results/final_v5/\n\n")
            handle.write("Commit: `%s`\n\n" % self.commit)
            handle.write("TOTAL TEST EXECUTIONS: %d\n\n" % total)
            handle.write("TOTAL PASSED: %d\n\n" % passed)
            handle.write("TOTAL FAILED: %d\n\n" % failed)
            handle.write("TOTAL SKIPPED: %d\n\n" % skipped)
            handle.write("TOTAL NOT_RUN: %d\n\n" % not_run)
            if not_run:
                handle.write("**TOTAL_NOT_RUN != 0 -- this campaign is NOT complete.**\n\n")
            handle.write("| Test ID | Category | Status |\n|---|---|---|\n")
            for row in self.rows:
                handle.write("| %s | %s | %s |\n" % (row["TEST_ID"], row["CATEGORY"], row["PASS_FAIL"]))
        return {"total": total, "passed": passed, "failed": failed, "skipped": skipped, "not_run": not_run}


def _run(cmd, ledger, test_id, category, case, expected, description):
    """Run a subprocess command, record it in the ledger, return (ok, proc)."""
    print("  [%s] %s" % (test_id, " ".join(cmd)))
    proc = subprocess.run(cmd, cwd=REPO_ROOT, capture_output=True, text=True)
    ok = proc.returncode == 0
    ledger.add(
        test_id=test_id, category=category, command=" ".join(cmd), case=case,
        expected=expected, actual=("exit 0" if ok else "exit %d: %s" % (proc.returncode, proc.stderr[-300:])),
        status="PASS" if ok else "FAIL",
        evidence_path=description,
    )
    if not ok:
        print("    FAILED (exit %d): %s" % (proc.returncode, proc.stderr[-500:]))
    return ok, proc


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--final-v5", action="store_true", required=True,
                         help="required, so this can never be invoked by accident")
    args = parser.parse_args(argv)

    os.makedirs(OUT_DIR, exist_ok=True)
    os.makedirs(os.path.join(OUT_DIR, "tests"), exist_ok=True)
    os.makedirs(os.path.join(OUT_DIR, "cross_environment"), exist_ok=True)

    ledger = Ledger()
    all_ok = True

    print("=" * 78)
    print("FINAL V5 CAMPAIGN -- commit %s" % ledger.commit)
    print("=" * 78)

    # ---- 1. Full pytest with JUnit XML -------------------------------------
    junit_path = os.path.join(OUT_DIR, "tests", "junit_full.xml")
    ok, proc = _run(
        [sys.executable, "-m", "pytest", "-q", "--junitxml=%s" % junit_path],
        ledger, "T-PYTEST", "test_suite", "all", "0 failures, 0 errors",
        os.path.relpath(junit_path, REPO_ROOT),
    )
    all_ok = all_ok and ok

    # ---- 2. The ten v1.2 experiment generators, each in final-v5 mode -----
    generators = [
        ("T-SURFACE-A", "experiments.surface_a_paired_validation", "surface_a", "8/8 nominal, 8/8 negative"),
        ("T-CASE-D", "experiments.case_d_matrix", "case_d", "10/10 (D1-D10)"),
        ("T-VALIDATORS", "experiments.validate_contract_v12", "validators", "16/16"),
        ("T-AUDIT", "experiments.audit_regression_v12", "audit", "Q1-Q10 10/10, 19+9 negatives detected"),
        ("T-DETERMINISM", "experiments.run_determinism_v12", "determinism", "155/155"),
        ("T-NEUTRALITY", "experiments.neutrality_v12", "neutrality", "all_passed=True"),
        ("T-TIMING", "experiments.compile_timing_v12", "compile_timing", "n=100 each case"),
        ("T-DIAGNOSTICS", "experiments.observation_diagnostics_v12", "observation_diagnostics", "both diagnostics pass"),
        ("T-CASE-B-INTEGRATION", "experiments.case_b_integration_regression_v12", "case_b_integration", "14/14"),
        ("T-MONTE-CARLO", "experiments.monte_carlo_regression_v12", "monte_carlo", "reproduces historical baseline"),
    ]
    for test_id, module, category, expected in generators:
        ok, proc = _run(
            [sys.executable, "-m", module, "--phase", PHASE, "--output", OUT_DIR],
            ledger, test_id, category, "all", expected,
            "results/final_v5/%s.json" % (category if category != "observation_diagnostics" else "observation_diagnostics"),
        )
        all_ok = all_ok and ok

    # ---- 3. Case B v1.1 determinism/Monte Carlo (paired with Case A) ------
    ok, proc = _run(
        [sys.executable, "-m", "experiments.run_determinism_case_b_v11", "--phase", PHASE, "--output", OUT_DIR],
        ledger, "T-DETERMINISM-CASE-B-V11", "determinism", "case_a+case_b_v1_1", "62/62 (TD=1.0)",
        "results/final_v5/determinism_summary_case_b_v11.json",
    )
    all_ok = all_ok and ok
    ok, proc = _run(
        [sys.executable, "-m", "experiments.run_monte_carlo_case_b_v11", "--phase", PHASE, "--output", OUT_DIR],
        ledger, "T-MONTE-CARLO-CASE-B-V11", "monte_carlo", "case_a+case_b_v1_1", "reproduces historical baseline",
        "results/final_v5/monte_carlo_summary_case_b_v11.json",
    )
    all_ok = all_ok and ok

    # ---- 4. Cross-environment evidence: copy with provenance, check currency
    current_head = ledger.commit
    cross_env_src = os.path.join(DEV_DIR, "cross_environment_determinism.json")
    cross_env_dst = os.path.join(OUT_DIR, "cross_environment_determinism.json")
    if os.path.exists(cross_env_src):
        shutil.copy2(cross_env_src, cross_env_dst)
        with open(cross_env_src, encoding="utf-8") as fh:
            cross_env_data = json.load(fh)
        evidence_sha = cross_env_data["result"].get("head_sha")
        current = evidence_sha == current_head
        ledger.add(
            "T-CROSS-ENV-CI", "cross_environment", "copy from results/development_v12/", "case_a/case_b_v1_1/case_d_ccs1",
            "head_sha == %s" % current_head,
            "head_sha == %s (%s)" % (evidence_sha, "CURRENT" if current else "STALE -- CI has not run against this exact commit"),
            "PASS" if current else "FAIL",
            "results/final_v5/cross_environment_determinism.json",
        )
        if not current:
            print("  [T-CROSS-ENV-CI] STALE: CI evidence is from commit %s, candidate is %s. "
                  "A real final freeze requires pushing this candidate commit and re-running CI." % (evidence_sha, current_head))
        all_ok = all_ok and current
    else:
        ledger.add("T-CROSS-ENV-CI", "cross_environment", "N/A", "all", "file present", "MISSING", "NOT_RUN", "")
        all_ok = False

    env7_src = os.path.join(DEV_DIR, "environment_container_aarch64.json")
    env7_dst = os.path.join(OUT_DIR, "environment_container_aarch64.json")
    if os.path.exists(env7_src):
        shutil.copy2(env7_src, env7_dst)
        with open(env7_src, encoding="utf-8") as fh:
            env7_data = json.load(fh)
        env7_ok = env7_data["verification"]["passed"] is True
        ledger.add(
            "T-CONTAINER", "cross_environment", "copy from results/development_v12/ (docker build + run)",
            "case_a/case_b_v1_1/case_d_ccs0/ccs1/ccs2",
            "155/155, all checks passed", "passed=%s" % env7_data["verification"]["passed"],
            "PASS" if env7_ok else "FAIL",
            "results/final_v5/environment_container_aarch64.json",
        )
        all_ok = all_ok and env7_ok
    else:
        ledger.add("T-CONTAINER", "cross_environment", "N/A", "all", "file present", "MISSING", "NOT_RUN", "")
        all_ok = False

    # ---- 5. Pre-freeze reconciliation documents (copied with provenance) --
    for name, src_name in (
        ("case_c_exclusion", "case_c_exclusion.json"),
        ("ccs2_temporal_provenance", "ccs2_temporal_provenance.json"),
        ("tacip_provenance_limitation", "tacip_provenance_limitation.json"),
        ("v110_eight_environment_reconciliation", "v110_eight_environment_reconciliation.json"),
    ):
        src = os.path.join(DEV_DIR, src_name)
        dst = os.path.join(OUT_DIR, src_name)
        present = os.path.exists(src)
        if present:
            shutil.copy2(src, dst)
        ledger.add(
            "T-DOC-%s" % name.upper(), "reconciliation_document", "copy from results/development_v12/",
            "all", "file present", "present" if present else "MISSING",
            "PASS" if present else "NOT_RUN", "results/final_v5/%s" % src_name,
        )
        all_ok = all_ok and present

    # ---- 6. Campaign aggregation -------------------------------------------
    ok, proc = _run(
        [sys.executable, "-m", "experiments.build_campaign_results_final_v5", "--input", OUT_DIR],
        ledger, "T-CAMPAIGN-AGGREGATION", "campaign", "all", "reportable=True",
        "results/final_v5/campaign_results.json",
    )
    all_ok = all_ok and ok

    # ---- 7. Freeze checker (independent re-verification) -------------------
    ok, proc = _run(
        [sys.executable, "tools/freeze_check.py", "--prospective-v5"],
        ledger, "T-FREEZE-CHECK", "freeze", "all", "PASS, 0 failures",
        "(stdout only; see this ledger row's ACTUAL field)",
    )
    all_ok = all_ok and ok

    summary = ledger.write(OUT_DIR)

    print("\n" + "=" * 78)
    print("FINAL V5 CAMPAIGN -- %s" % ("ALL MANDATORY STEPS PASSED" if all_ok else "FAILED / INCOMPLETE"))
    print("TOTAL=%d PASSED=%d FAILED=%d SKIPPED=%d NOT_RUN=%d"
          % (summary["total"], summary["passed"], summary["failed"], summary["skipped"], summary["not_run"]))
    print("=" * 78)

    return 0 if (all_ok and summary["not_run"] == 0) else 1


if __name__ == "__main__":
    raise SystemExit(main())
